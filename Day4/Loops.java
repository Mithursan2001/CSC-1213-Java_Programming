class Loops{
	public static void main(String args[]){		
		//print numbers from 0-10 
		
		//for loop
		for(int i=0; i<=10; i++){
			System.out.println(i);
		}
		
		//while loop
		int j=0;
		while(j<=10){
			System.out.println(j);
			j++;
		}
		
		//Q1: Find sum of numbers from 1-10
		//Q2: Find sum of even numbers from 5-20
		//Q3: Find sum of positive numbers until user inputs a negative numbers
		//Q4: Print numbers 1-10 except 4&6
	}
}